def add_income_fy22(
    df: pd.DataFrame,
    iso3_col: str = "iso3_code",
    income_level_col: str = "income_level",
) -> pd.DataFrame:
    """Add FY22 income level to a dataframe based on ISO3 codes"""

    return df.assign(**{income_level_col: df[iso3_col].map(FY22_INCOME_DICT)})


