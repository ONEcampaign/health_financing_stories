def read_ghed_data() -> pd.DataFrame:

    path = Paths.raw_data / "ghed_data.csv"

    if not path.exists():
        logger.info("GHED data not found, fetching...")
        fetch_ghed_data()

    logger.info("Reading GHED data...")
    return pd.read_csv(path)


